export type ToolStatus = 'ready' | 'planned';

export interface ToolMeta {
  id: string;
  title: string;
  description: string;
  href: string;
  category: ToolCategory;
  icon: LucideIcon;
  status: ToolStatus;
  /** 구현 Phase 로 정렬. 1 = 우선순위 최상위. */
  phase: 1 | 2 | 3 | 4 | 5 | 6 | 7;
  /** 검색에서 매칭될 추가 키워드 (한/영) */
  keywords?: string[];
  /** 도구가 registry 에 추가된 날짜 (ISO yyyy-mm-dd). NEW 배지·신규순 정렬에 사용. */
  addedAt?: string;
}

