const HANGUL_BASE = 0xac00;
// 두음법칙: 초성 ㄹ(5)/ㄴ(2) + 특정 중성
// 중성 인덱스: ㅑ2 ㅒ3 ㅕ6 ㅖ7 ㅛ12 ㅠ17 ㅣ20
const IOTIZED = new Set([2, 3, 6, 7, 12, 17, 20]);
const CHO_N = 2;
const CHO_R = 5;
const CHO_NG = 11;

/** 단어 첫머리 두음법칙 적용 (녀→여, 리→이, 로→노 …) */
export function applyInitialSoundRule(syllable: string): string {
  const code = syllable.charCodeAt(0) - HANGUL_BASE;
  if (code < 0 || code > 11171) return syllable;
  const cho = Math.floor(code / 588);
  const jung = Math.floor((code % 588) / 28);
  const jong = code % 28;
  let next = cho;
  if (cho === CHO_R) next = IOTIZED.has(jung) ? CHO_NG : CHO_N;
  else if (cho === CHO_N && IOTIZED.has(jung) && jung !== 2 && jung !== 3 && jung !== 7) next = CHO_NG;
  if (next === cho) return syllable;
  return String.fromCharCode(HANGUL_BASE + next * 588 + jung * 28 + jong);
}

function isHanja(ch: string | undefined): boolean {
  if (!ch) return false;
  const c = ch.codePointAt(0) ?? 0;
  return (c >= 0x4e00 && c <= 0x9fff) || (c >= 0x3400 && c <= 0x4dbf) || (c >= 0xf900 && c <= 0xfaff);
}

/**
 * 텍스트 안의 한자를 한글 독음으로 바꾼다. 사전에 없는 한자는 그대로 둔다.
 * 한자 연속 구간의 첫 글자(=단어 첫머리)에는 두음법칙을 적용한다.
 */
export function hanjaToHangul(text: string): { result: string; replacements: number } {
  const d = dict();
  let count = 0;
  let out = '';
  let prev: string | undefined;
  for (const ch of text) {
    const reading = d.get(ch);
    if (reading) {
      out += isHanja(prev) ? reading : applyInitialSoundRule(reading);
      count++;
    } else {
      out += ch;
    }
    prev = ch;
  }
  return { result: out, replacements: count };
}
