const TEXT_ANALYSIS_KEYS = new Set([
  'text-diff',
  'text-count',
  'regex-tester',
  'jwt-decoder',
  'json-format',
  'base64',
  'cron-explainer',
  'markdown-stats',
  'url-parser',
  'url-encoder',
  'jsonpath',
  'sql-format',
  'html-entities',
  // 오피스 입력형 도구 (Input → Result → Copy)
  'redact',
  'excel-formula',
]);

export function getPattern(tool: ToolMeta): GuidePattern {
  if (GENERATOR_KEYS.has(tool.id)) return 'generator';
  if (CALC_KEYS.has(tool.id)) return 'calc';
  if (VIEWER_KEYS.has(tool.id)) return 'viewer';
  if (TEXT_ANALYSIS_KEYS.has(tool.id)) return 'text';
  // text 카테고리 + 자체 입력형 도구는 대부분 text-analysis
  if (tool.category === 'text' || tool.category === 'dev' || tool.category === 'util') {
    // hash·file-hash 처럼 파일 입력 받는 일부는 file 패턴
    if (tool.id === 'file-hash') return 'file';
    return 'text';
  }
  return 'file';
}

export interface GuideStep {
  title: string;
  body: string;
}

export interface GuideContent {
  /** 메타 title (35자 이내) */
  metaTitle: string;
  /** 메타 description (150자 이내) */
  metaDescription: string;
  /** H1 + 도입 한 줄 요약 */
  intro: string;
  /** 핵심 기능 bullet 3~5개 */
  features: string[];
  /** 단계별 사용법 */
  steps: GuideStep[];
  /** 도구별 FAQ */
  faqs: Array<{ q: string; a: string }>;
}

/**
 * 도구별 맞춤 가이드 본문(override).
 *
 * 패턴 자동생성은 "어떤 도구에나 맞는" 일반 문장이라 long-tail SEO·체류시간에
 * 약하다. 검색 수요가 큰 도구는 여기에 실제 사용 시나리오·예시·함정을 담은
 * 도구별 본문을 작성해 자동생성 결과 위에 덮어쓴다.
 *
 * 지정한 필드만 교체되고, 생략한 필드는 자동생성 본문이 그대로 쓰인다.
 * `faqs` 를 주면 도구별 FAQ 가 먼저 오고 공통 FAQ(개인정보·무료·모바일)가
 * 뒤에 자동으로 붙는다.
 */
export interface GuideOverride {
  metaTitle?: string;
  metaDescription?: string;
  intro?: string;
  features?: string[];
  steps?: GuideStep[];
  /** 도구별 FAQ. 공통 FAQ 3종이 자동으로 뒤에 추가된다. */
  faqs?: Array<{ q: string; a: string }>;
}

