/**
 * 검색 라이트 인덱스 생성기 (prebuild).
 *
 * 변환·비교·활용법 데이터(convert-matrix·ko-compares·use-cases)는 4개국어(ko·en·ja·zh)
 * SEO 본문을 품고 있어 무겁다. 이 데이터를 **클라이언트** 컴포넌트(CommandPalette·
 * ToolConvertLinks, 전 페이지/도구 페이지 마운트)가 직접 import 하면 그 다국어 본문이
 * 공유 클라이언트 번들에 통째로 들어간다(언어 추가마다 누적 증가).
 *
 * 이 스크립트는 빌드 시점에 실제 타입 데이터를 읽어, 클라이언트가 검색·역링크에
 * 실제로 쓰는 최소 필드(slug·라벨·ko 제목·키워드·매핑)만 담은 정적 모듈
 * `src/lib/search-index.generated.ts` 를 만든다. 두 컴포넌트는 이 라이트 인덱스만
 * import 하므로 무거운 데이터 모듈은 **서버 전용**이 되어 클라이언트 번들에서 빠진다.
 *
 * 실행: Node 24 네이티브 TS + `ts-resolve-hook`(@/ 별칭 해석). `npm run search:gen`.
 */

import { register } from 'node:module';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve as resolvePath, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
register('./ts-resolve-hook.mjs', pathToFileURL(join(here, '/')));

const importTs = (rel) =>
  import(pathToFileURL(resolvePath(here, '..', rel)).href);

const { CONVERSIONS, FORMATS, conversionSlug } = await importTs('src/lib/convert-matrix.ts');
const { USE_CASES } = await importTs('src/lib/use-cases.ts');
const { COMPARES_KO } = await importTs('src/lib/ko-compares.ts');

/** 변환: 검색 + 도구→변환 역링크. 클라이언트는 slug·라벨·toolId 만 필요. */
const convert = CONVERSIONS.map((c) => ({
  slug: conversionSlug(c),
  label: `${FORMATS[c.from].label} → ${FORMATS[c.to].label}`,
  from: c.from,
  to: c.to,
  toolId: c.toolId,
}));

/** 비교: 검색(h1·키워드) + 도구→비교 역링크(옵션 toolId). ko 제목만. */
const compare = COMPARES_KO.map((c) => ({
  slug: c.slug,
  h1: c.h1,
  keywords: c.keywords ?? [],
  toolIds: [...new Set(c.options.map((o) => o.toolId).filter(Boolean))],
}));

/** 활용법: 검색(h1·설명·키워드) + 도구→활용법 역링크(단계 경로). ko 만. */
const usecase = USE_CASES.map((u) => ({
  slug: u.slug,
  h1: u.h1.ko,
  description: u.description.ko,
  keywords: u.keywords.ko ?? [],
  stepHrefs: [...new Set(u.steps.map((s) => s.href.split('?')[0]))],
}));

const banner = `// AUTO-GENERATED by scripts/generate-search-index.mjs — DO NOT EDIT.
// 클라이언트 검색·역링크용 라이트 인덱스(다국어 본문 제외). \`npm run search:gen\` 또는 prebuild 로 재생성.
/* eslint-disable */`;

const body = `${banner}

export interface ConvertEntry { slug: string; label: string; from: string; to: string; toolId: string; }
export interface CompareEntry { slug: string; h1: string; keywords: string[]; toolIds: string[]; }
export interface UseCaseEntry { slug: string; h1: string; description: string; keywords: string[]; stepHrefs: string[]; }

export const CONVERT_INDEX: ConvertEntry[] = ${JSON.stringify(convert)};

export const COMPARE_INDEX: CompareEntry[] = ${JSON.stringify(compare)};

export const USECASE_INDEX: UseCaseEntry[] = ${JSON.stringify(usecase)};
`;

const outDir = resolvePath(here, '..', 'src/lib');
mkdirSync(outDir, { recursive: true });
const outPath = join(outDir, 'search-index.generated.ts');
writeFileSync(outPath, body, 'utf-8');

console.log(
  `검색 인덱스 생성: 변환 ${convert.length} · 비교 ${compare.length} · 활용법 ${usecase.length} → src/lib/search-index.generated.ts`,
);
